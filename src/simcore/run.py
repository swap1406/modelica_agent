"""run_simulation(): run one Modelica model in OpenModelica, in its own run folder.

Each run produces a folder like  results/runs/20261010-153012_MBEV/  containing:
    run.mos        the exact OpenModelica script that was executed (reproducible)
    console.txt    everything OpenModelica printed
    <Model>_res.csv   the simulation results (if the run succeeded)
    <Model>.log    the simulation log
    <Model>_init.xml  OpenModelica's list of all variables with descriptions and units
    run.json       the run record: model, settings, status, messages, timings, versions
    build/         OpenModelica's intermediate files (generated C code, compiled program).
                   Deleted after a successful run unless keep_build=True; always kept
                   when a run fails, so the cause can be investigated.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import time
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path

from simcore import config
from simcore.environment import environment_info


@dataclass
class RunResult:
    """Everything we know about one simulation run."""

    run_id: str                      # e.g. "20261010-153012_MBEV"
    model: str                       # full Modelica name, e.g. "EHPTexamples.EV.MBEV"
    status: str                      # "success" or "failed"
    run_dir: str                     # folder holding all files of this run
    result_file: str | None          # path to the results CSV, None if failed
    stop_time: float | None          # None = the model's own default
    simflags: str | None             # extra simulation flags, if any
    build_dir: str | None = None     # kept build files (C code etc.), None if cleaned up
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    notifications: list[str] = field(default_factory=list)
    duration_s: float = 0.0          # wall-clock time for the whole run
    started_at: str = ""
    environment: dict = field(default_factory=dict)

    def summary(self) -> str:
        """A short human-readable summary, e.g. for printing in Terminal."""
        lines = [
            f"Run      : {self.run_id}",
            f"Model    : {self.model}",
            f"Status   : {self.status.upper()}",
            f"Duration : {self.duration_s:.1f} s",
            f"Results  : {self.result_file or '-'}",
            f"Build    : {self.build_dir or 'cleaned up'}",
            f"Errors   : {len(self.errors)}   Warnings: {len(self.warnings)}",
        ]
        for e in self.errors:
            lines.append(f"  ERROR   {e.splitlines()[0][:150]}")
        for w in self.warnings:
            lines.append(f"  WARNING {w.splitlines()[0][:150]}")
        return "\n".join(lines)


def _new_run_dir(model: str) -> tuple[str, Path]:
    """Create a unique, dated folder for this run."""
    short_name = model.split(".")[-1]
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    run_id = f"{stamp}_{short_name}"
    run_dir = config.RUNS_DIR / run_id
    n = 2
    while run_dir.exists():  # two runs in the same second: add a counter
        run_id = f"{stamp}_{short_name}_{n}"
        run_dir = config.RUNS_DIR / run_id
        n += 1
    run_dir.mkdir(parents=True)
    return run_id, run_dir


def _build_script(model: str, build_dir: Path, stop_time: float | None, simflags: str | None) -> str:
    """Write the OpenModelica script (.mos) for this run."""
    lines = [
        f"// Generated by simcore for model {model}",
        "// 1. Modelica Standard Library (cached in .om-home after the first download)",
        f'installPackage(Modelica, "{config.MSL_VERSION}+maint.om", exactMatch=false); getErrorString();',
        f'loadModel(Modelica, {{"{config.MSL_VERSION}"}}); getErrorString();',
        "// 2. Libraries and our own models",
    ]
    files = list(config.LIBRARY_FILES) + sorted(config.MODELS_DIR.glob("*.mo"))
    for f in files:
        if Path(f).exists():
            lines.append(f'loadFile("{f}"); getErrorString();')
    lines.append("// 3. Simulate in a temporary build folder")
    lines.append(f'cd("{build_dir}");')
    args = [model, 'outputFormat="csv"', f'fileNamePrefix="{model.split(".")[-1]}"']
    if stop_time is not None:
        args.append(f"stopTime={stop_time}")
    if simflags:
        args.append(f'simflags="{simflags}"')
    lines.append(f"simulate({', '.join(args)}); getErrorString();")
    return "\n".join(lines) + "\n"


_MSG_START = re.compile(r'^"?(Error|Warning|Notification): ?(.*)')


def _sort_messages(output: str) -> tuple[list[str], list[str], list[str]]:
    """Split OpenModelica's output into errors, warnings and notifications (no duplicates).

    A message starts with 'Error:', 'Warning:' or 'Notification:'; following lines that are
    indented belong to the same message.
    """
    buckets: dict[str, list[str]] = {"Error": [], "Warning": [], "Notification": []}
    current_kind, current_lines = None, []

    def flush():
        if current_kind:
            text = "\n".join(current_lines).strip().rstrip('"').strip()
            if text and text not in buckets[current_kind]:
                buckets[current_kind].append(text)

    for line in output.splitlines():
        m = _MSG_START.match(line.strip())
        if m:
            flush()
            current_kind, current_lines = m.group(1), [m.group(2)]
        elif current_kind and line.startswith((" ", "\t")) and line.strip():
            current_lines.append(line.strip())
        else:
            flush()
            current_kind, current_lines = None, []
    flush()
    return buckets["Error"], buckets["Warning"], buckets["Notification"]


def run_simulation(model: str, stop_time: float | None = None, simflags: str | None = None,
                   keep_build: bool = False, timeout_s: int = 900) -> RunResult:
    """Run one Modelica model and return a RunResult.

    model      full Modelica name, e.g. "EHPTexamples.EV.MBEV" or "HelloEV"
    stop_time  simulation end time in seconds; None uses the model's own setting
    simflags   extra OpenModelica simulation flags, e.g. "-jacobian=coloredNumerical"
    keep_build keep OpenModelica's intermediate files in build/ (always kept on failure)
    timeout_s  give up after this many seconds
    """
    started = time.time()
    run_id, run_dir = _new_run_dir(model)
    build_dir = run_dir / "build"
    build_dir.mkdir()
    short_name = model.split(".")[-1]

    # 1. Write the script, so the run is reproducible and inspectable
    script = run_dir / "run.mos"
    script.write_text(_build_script(model, build_dir, stop_time, simflags))

    # 2. Run OpenModelica on it and keep everything it prints
    try:
        proc = subprocess.run(["omc", str(script)], capture_output=True, text=True, timeout=timeout_s)
        output = proc.stdout + proc.stderr
    except subprocess.TimeoutExpired:
        output = f"Error: simulation timed out after {timeout_s} s"
    (run_dir / "console.txt").write_text(output)

    # 3. Move the results and log up into the run folder
    result_csv, log_file = build_dir / f"{short_name}_res.csv", build_dir / f"{short_name}.log"
    log_text = log_file.read_text(errors="replace") if log_file.exists() else ""
    kept_csv = None
    if result_csv.exists():
        kept_csv = run_dir / result_csv.name
        shutil.move(str(result_csv), kept_csv)
    if log_file.exists():
        shutil.move(str(log_file), run_dir / log_file.name)
    init_xml = build_dir / f"{short_name}_init.xml"   # variable descriptions + units
    if init_xml.exists():
        shutil.copy2(init_xml, run_dir / init_xml.name)

    # 4. Decide success: a results file AND the log confirms the simulation finished
    errors, warnings, notifications = _sort_messages(output)
    success = kept_csv is not None and "simulation finished successfully" in log_text

    # 5. Build clutter: delete after success (unless asked to keep), always keep after failure
    if success and not keep_build:
        shutil.rmtree(build_dir, ignore_errors=True)
        kept_build = None
    else:
        kept_build = str(build_dir)
    if not success and log_text:
        # Runtime problems are reported in the log, not the console: surface them too
        errors += [l.strip() for l in log_text.splitlines() if "| error" in l][:10]
    if not success and not errors:
        # Never return a silent failure: say at least what we know
        errors.append("Simulation failed: no results file was produced. See console.txt in the run folder.")

    result = RunResult(
        run_id=run_id,
        model=model,
        status="success" if success else "failed",
        run_dir=str(run_dir),
        result_file=str(kept_csv) if kept_csv else None,
        stop_time=stop_time,
        simflags=simflags,
        build_dir=kept_build,
        errors=errors,
        warnings=warnings,
        notifications=notifications,
        duration_s=round(time.time() - started, 2),
        started_at=datetime.fromtimestamp(started).isoformat(timespec="seconds"),
        environment=environment_info(),
    )

    # 6. Save the run record next to the results
    (run_dir / "run.json").write_text(json.dumps(asdict(result), indent=2))
    return result
